"""Export of the explorer's data from the current cloud database (Supabase) to one SQL file for a self-hosted
PostgreSQL (deploy/onprem/README.md, "Transfer of the current data").

Run by Agilos, from the root of the repository:
    python deploy/onprem/export_data.py --out tsi-explorer-data.sql [--schema tsi_explorer]
Reads SUPABASE_URL and SUPABASE_SERVICE_KEY from the environment or from .env (never from a file in Git).

The SQL file is loaded on the target database, after deploy/onprem/sql/000_compat.sql and supabase/migrations/001
to 010, with: psql -v ON_ERROR_STOP=1 -f tsi-explorer-data.sql
It runs in one transaction: it empties the explorer's tables, loads every row (users, reviews, usage data and
impact analyses included), sets the id counters and prints the row counts. It contains personal data (users'
e-mail addresses): never commit it, send it through a secure channel.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import secrets
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

# (table, sort key, columns computed by the database and therefore not exported). Parents before children.
TABLES: list[tuple[str, str, tuple[str, ...]]] = [
    ("csr_documents", "doc_id", ()),
    ("csrs", "csr_id", ("fts",)),
    ("csr_parts", "part_id", ()),
    ("projects", "project_id", ("fts",)),
    ("project_csr_links", "project_id,part_id", ()),
    ("csr_related_projects", "csr_id,project_id", ()),
    ("anomalies", "id", ()),
    ("impact_reports", "id", ()),
    ("testers", "email", ()),
    ("link_reviews", "id", ()),
    ("page_views", "id", ()),
    ("csr_recitals", "recital_id", ("fts",)),
    ("country_reports", "report_id", ()),
    ("country_report_passages", "passage_id", ("fts",)),
]
IDENTITY = {"anomalies", "impact_reports", "link_reviews", "page_views"}  # "id" generated by the database
PAGE = 1000  # rows per request (the cloud API's maximum)
CHUNK = 500  # rows per INSERT statement


def settings() -> tuple[str, str]:
    values = {}
    dotenv = Path(".env")
    if dotenv.exists():
        for line in dotenv.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.strip().startswith("#"):
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip().strip("'\"")
    url = os.environ.get("SUPABASE_URL") or values.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_KEY") or values.get("SUPABASE_SERVICE_KEY")
    if not url or not key:
        sys.exit("SUPABASE_URL and SUPABASE_SERVICE_KEY are required (environment or .env)")
    return url.rstrip("/"), key


def fetch(url: str, key: str, table: str, order: str) -> list[dict]:
    headers = {"apikey": key, "Accept": "application/json"}
    if not key.startswith("sb_"):
        headers["Authorization"] = f"Bearer {key}"
    order_by = ",".join(f"{col}.asc" for col in order.split(","))
    rows: list[dict] = []
    while True:
        req = urllib.request.Request(
            f"{url}/rest/v1/{table}?select=*&order={order_by}&offset={len(rows)}&limit={PAGE}", headers=headers)
        with urllib.request.urlopen(req, timeout=120) as resp:
            page = json.load(resp)
        rows += page
        if len(page) < PAGE:
            return rows


def inserts(table: str, rows: list[dict], skip: tuple[str, ...], schema: str = "public") -> list[str]:
    cols = [c for c in rows[0] if c not in skip]
    col_list = ", ".join(f'"{c}"' for c in cols)
    overriding = " overriding system value" if table in IDENTITY else ""
    out = []
    for i in range(0, len(rows), CHUNK):
        payload = json.dumps([{c: r.get(c) for c in cols} for r in rows[i:i + CHUNK]], ensure_ascii=False)
        tag = "tsi"
        while f"${tag}$" in payload:
            tag = "tsi_" + secrets.token_hex(4)
        out.append(f"insert into {schema}.{table} ({col_list}){overriding}\n  select {col_list} from "
                   f"json_populate_recordset(null::{schema}.{table}, ${tag}${payload}${tag}$);")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="SQL file to write (not in the repository)")
    parser.add_argument("--schema", default="public", help="schema of the tables on the target database (default public)")
    args = parser.parse_args()
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", args.schema):
        sys.exit("The schema name must be lower case letters, digits and _")
    sc = args.schema
    url, key = settings()
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    names = [t for t, _, _ in TABLES]
    counts: dict[str, int] = {}
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"-- TSI x CSR Explorer: data export of {now}.\n"
                "-- Load AFTER deploy/onprem/sql/000_compat.sql and supabase/migrations/001 to 010:\n"
                "--   psql -v ON_ERROR_STOP=1 -f <this file>\n"
                "-- Replaces all the explorer's rows. Contains personal data (e-mail addresses): keep it private.\n\n"
                "\\set ON_ERROR_STOP on\nbegin;\n"
                f"truncate table {', '.join(f'{sc}.{n}' for n in names)};\n\n")
        for table, order, skip in TABLES:
            rows = fetch(url, key, table, order)
            counts[table] = len(rows)
            print(f"{table:28} {len(rows):>7} rows", file=sys.stderr)
            if rows:
                f.write(f"-- {table}: {len(rows)} rows\n" + "\n".join(inserts(table, rows, skip, sc)) + "\n\n")
        for table in sorted(IDENTITY):
            f.write(f"select setval(pg_get_serial_sequence('{sc}.{table}', 'id'), "
                    f"coalesce(max(id), 1), max(id) is not null) from {sc}.{table};\n")
        f.write("commit;\n" + "".join(f"analyze {sc}.{n};\n" for n in names) + "\n-- Row counts after loading (expected values in the comments).\n")
        f.write("\nunion all\n".join(f"select '{t}' as table_name, count(*) as rows, {counts[t]} as expected "
                                     f"from {sc}.{t}" for t in names) + ";\n")
    print(f"written {args.out}: {sum(counts.values())} rows in {len(names)} tables", file=sys.stderr)


if __name__ == "__main__":
    main()
